#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""gen_font16.py —— 用本机 Consolas 字体生成 ASCII 8x16 点阵 C 数组

产物:
    src/font16.c   数据 (font16[95][16], ASCII 32..126, bit7=最左像素)
    src/font16.h   声明
运行:  python gen_font16.py   （Windows, 需要 Pillow）
"""
import os

from PIL import Image, ImageDraw, ImageFont

BASE = os.path.dirname(os.path.abspath(__file__))
FONT_PATH = r"C:\Windows\Fonts\consola.ttf"   # Consolas，Win10/11 自带
PX = 13                                        # 13px 正好放进 8x16 单元格

font = ImageFont.truetype(FONT_PATH, PX)
img = Image.new("1", (8, 16), 0)
draw = ImageDraw.Draw(img)

rows = []
empty = []
for code in range(32, 127):
    draw.rectangle([0, 0, 7, 15], fill=0)
    draw.text((0, 0), chr(code), font=font, fill=1)
    glyph = []
    for y in range(16):
        v = 0
        for x in range(8):
            if img.getpixel((x, y)):
                v |= 0x80 >> x
        glyph.append(v)
    if not any(glyph):
        empty.append(chr(code))
    rows.append((code, glyph))

lines = [
    "/*",
    " * font16.c -- ASCII 8x16 dot-matrix font (95 glyphs, ASCII 32..126)",
    " * generated by gen_font16.py (Consolas 13px via Pillow), 2026-11-02",
    " */",
    '#include "font16.h"',
    "",
    "const unsigned char font16[95][16] = {",
]
for code, glyph in rows:
    ch = chr(code)
    label = "space" if code == 32 else ("backslash" if ch == "\\" else ch)
    body = ",".join("0x%02x" % v for v in glyph)
    end = "}" if code == 126 else "},"
    lines.append("    /* %3d 0x%02x %s */ {%s%s" % (code, code, label, body, end))
lines.append("};")
lines.append("")

with open(os.path.join(BASE, "src", "font16.c"), "w", encoding="ascii") as f:
    f.write("\n".join(lines))

with open(os.path.join(BASE, "src", "font16.h"), "w", encoding="ascii") as f:
    f.write(
        "#ifndef FONT16_H\n"
        "#define FONT16_H\n"
        "/* ASCII 8x16 dot-matrix font, index = ch - 32 (32..126) */\n"
        "extern const unsigned char font16[95][16];\n"
        "#endif\n"
    )

print("glyphs:", len(rows), "| empty glyphs:", empty if empty else "none")
print("space all-zero:", all(v == 0 for v in rows[0][1]))
print("sample 'A':", " ".join("0x%02x" % v for v in rows[65 - 32][1]))
