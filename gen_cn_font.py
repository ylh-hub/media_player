#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""gen_cn_font.py -- 用 Windows 宋体渲染 16x16 中文点阵，生成 C 数组

字符来源: lrc/*.lrc 歌词文件 + 下方 UI_STRINGS 界面固定字符串
产物:     src/font_cn.c / src/font_cn.h
运行:     python gen_cn_font.py   (Windows, 需要 Pillow)
以后加新歌词/新界面文字 -> 重跑本脚本即可。
"""
import glob
import os

from PIL import Image, ImageDraw, ImageFont

BASE = os.path.dirname(os.path.abspath(__file__))
FONT_PATH = r"C:\Windows\Fonts\simsun.ttc"   # 宋体，Win 自带

# 界面固定中文字符串（新增界面文字就加到这里）
UI_STRINGS = [
    "播放列表",
    "退出程序",
    "视频",
    "菜单",
    "无歌词",
    "歌曲",
    "葫芦娃",
    "蓝精灵",
    "两只老虎",
    "起风了",
]

def collect_chars():
    chars = set()
    for s in UI_STRINGS:
        chars.update(s)
    for f in glob.glob(os.path.join(BASE, "lrc", "*.lrc")):
        with open(f, "r", encoding="utf-8") as fh:
            chars.update(fh.read())
    chars.discard("\n")
    chars.discard("\r")
    chars.discard(" ")
    chars.discard("[")
    chars.discard("]")
    chars.discard(".")
    chars.discard(":")
    return sorted(chars)

def main():
    chars = collect_chars()
    font = ImageFont.truetype(FONT_PATH, 16)
    img = Image.new("1", (16, 16), 0)
    draw = ImageDraw.Draw(img)

    entries = []          # (codepoint, bytes16x16)
    empty = []
    for ch in chars:
        cp = ord(ch)
        draw.rectangle([0, 0, 15, 15], fill=0)
        draw.text((0, 0), ch, font=font, fill=1)
        glyph = bytearray(32)
        any_bit = False
        for row in range(16):
            for col in range(16):
                if img.getpixel((col, row)):
                    glyph[row * 2 + (col >> 3)] |= 0x80 >> (col & 7)
                    any_bit = True
        if not any_bit:
            empty.append(ch)
        entries.append((cp, bytes(glyph)))

    entries.sort(key=lambda e: e[0])

    lines = [
        "/*",
        " * font_cn.c -- Chinese 16x16 dot-matrix glyphs (SimSun 16px via Pillow)",
        " * generated by gen_cn_font.py from lrc/*.lrc + UI_STRINGS, 2026-11-03",
        " * lookup: codepoint array is sorted, use binary search (see fb_ui.c)",
        " */",
        '#include "font_cn.h"',
        "",
        "const int cn_font_count = %d;" % len(entries),
        "",
        "const unsigned int cn_cp[%d] = {" % len(entries),
    ]
    for i in range(0, len(entries), 8):
        row = ",".join("0x%04x" % cp for cp, _ in entries[i:i + 8])
        lines.append("    " + row + ",")
    lines.append("};")
    lines.append("")
    lines.append("const unsigned char cn_glyph[%d][32] = {" % len(entries))
    for cp, glyph in entries:
        body = ",".join("0x%02x" % b for b in glyph)
        lines.append("    {%s},   /* U+%04X %s */" % (body, cp, chr(cp)))
    lines.append("};")
    lines.append("")

    with open(os.path.join(BASE, "src", "font_cn.c"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    with open(os.path.join(BASE, "src", "font_cn.h"), "w", encoding="ascii") as f:
        f.write(
            "#ifndef FONT_CN_H\n"
            "#define FONT_CN_H\n"
            "/* Chinese 16x16 glyphs, sorted by codepoint, binary search */\n"
            "extern const int cn_font_count;\n"
            "extern const unsigned int cn_cp[];\n"
            "extern const unsigned char cn_glyph[][32];\n"
            "#endif\n"
        )

    print("chars embedded:", len(entries))
    print("empty glyphs:", empty if empty else "none")
    print("sample:", " ".join(chr(cp) for cp, _ in entries[:12]))

if __name__ == "__main__":
    main()
